/* ───────────────────────────────────────────────────────────────────
 * 六、敌人显示名统一分发（战斗/地图/图鉴等所有玩家可见名称的唯一出口）
 *   传入的是【稳定 id】：
 *     m_xxx  → 怪物显示名（monsterName）
 *     b_xxx  → Boss 显示名（bossName）
 *     其它    → 随从/召唤物显示名（summonName，旧中文 key → 新显示名）
 *   这样代码里只需 enemyDisplayName(e.name)，永远显示中枢里的名字，
 *   改名字只动本文件，调用处无需任何修改。
 * ─────────────────────────────────────────────────────────────────── */
export const enemyDisplayName = (id: string): string =>
  id.startsWith('m_') ? monsterName(id)
  : id.startsWith('b_') ? bossName(id)
  : summonName(id);

/** NPC 显示名（id 形如 npc_m01；系统 NPC 无中枢条目时回退原 id） */
export const npcDisplayName = (id: string): string => npcName(id);
